#!/usr/bin/env python3
"""Write engines/vision/report/vis-setups.tsv: which llama-swap entries load a vision head or tower, and where.

  python3 -I make_setups.py REPO LLAMA_SWAP_YAML_COPY DRY_RUN_TXT OUT_TSV

Reads, never writes, the inputs:
  - a read-only copy of Titan's llama-swap.yaml (the entries configured today),
  - engines/vision/vis-entries/dry-run.txt (the planned <entry>-vis entries, cmd as the tool would write it),
  - the catalog (REPO/tools/catalog.py) to map an entry to its model record.
One row per entry that sees images. `status` is configured (in the yaml) or planned (only in the dry run).
`place`: gpu (projector on the GPU), cpu (llama.cpp --no-mmproj-offload), host-ram (engine keeps the tower in pinned
host RAM), built-in (engine-managed tower inside the checkpoint, not separated), gpu-default (vLLM loads the tower on
the GPU because nothing turns it off).
"""
import hashlib, os, re, sys
import yaml

REPO, YAML, DRY, OUT = sys.argv[1:5]
sys.path.insert(0, os.path.join(REPO, "tools"))
import catalog  # noqa: E402

MM = re.compile(r"(?:^|\s)(?:-mm|--mmproj)\s+(\S+)")


def setup(eid, cmd, env):
    """(place, head_file, flags) for one entry's cmd, or None when the entry is blind."""
    text = cmd + "\n" + "\n".join(env or [])
    m = MM.search(text)
    if m:
        off = "--no-mmproj-offload" in text
        return ("cpu" if off else "gpu"), os.path.basename(m.group(1)), ("--mmproj --no-mmproj-offload" if off else "--mmproj")
    if "TABBY_MODEL_VISION=true" in text:
        off = "TABBY_MODEL_VISION_OFFLOAD=true" in text
        return ("host-ram" if off else "gpu"), "(in checkpoint)", "TABBY_MODEL_VISION=true" + (" TABBY_MODEL_VISION_OFFLOAD=true" if off else "")
    if re.search(r"-e VISION=1\b", text):
        off = re.search(r"-e VISION_OFFLOAD=1\b", text)
        return ("host-ram" if off else "gpu"), "(in checkpoint)", "VISION=1" + (" VISION_OFFLOAD=1" if off else "")
    if "SGLANG_EXL3_VISION=1" in text:
        return "built-in", "(in checkpoint)", "SGLANG_EXL3_VISION=1"
    if "/app/venv/bin/vllm" in text and re.search(r"\bserve\b", text) and "--language-model-only" not in text:
        key, rec = catalog.model_of_entry(eid)
        if rec and (rec.get("vision") or {}).get("supported"):
            return "gpu-default", "(in checkpoint)", "(vLLM default: images on)"
    return None


rows = []
cfg = yaml.safe_load(open(YAML))["models"]
for eid, v in sorted(cfg.items()):
    s = setup(eid, v.get("cmd") or "", v.get("env"))
    if s:
        rows.append((eid, eid, catalog.model_of_entry(eid)[0] or "", "configured") + s + ("llama-swap.yaml copy",))

dry = open(DRY).read()
head = dry.split("\n### yaml\n", 1)[1].split("\n### spec ", 1)[0]
planned = yaml.safe_load("models:\n" + head)["models"]
for eid, v in sorted(planned.items()):
    if eid in cfg: continue
    src = re.search(r"Vision variant of (\S+) \(", v.get("description") or "")
    src = src.group(1) if src else eid[:-4]
    s = setup(src, v.get("cmd") or "", v.get("env"))
    if s:
        rows.append((eid, src, catalog.model_of_entry(src)[0] or "", "planned") + s + ("vis-entries/dry-run.txt",))

# the yaml copy read here, and the yaml the dry run was made from (its "# yaml <path> sha256 <hex>" line)
ysha = hashlib.sha256(open(YAML, "rb").read()).hexdigest()
dsha = re.search(r"^# yaml \S+ sha256 ([0-9a-f]{64})", dry, re.M)
dsha = dsha.group(1) if dsha else "?"
if dsha != ysha:
    print(f"!! the dry run was made from yaml sha256 {dsha[:12]}, the copy read here is {ysha[:12]}", file=sys.stderr)
with open(OUT, "w") as f:
    f.write(f"# generated by engines/vision/report/make_setups.py from a llama-swap.yaml copy (sha256 {ysha[:12]}) and"
            f" vis-entries/dry-run.txt (made from yaml sha256 {dsha[:12]}); do not edit by hand\n")
    f.write("entry\tsource_entry\trecord\tstatus\tplace\thead_file\tflags\tevidence\n")
    for r in rows: f.write("\t".join(r) + "\n")
print(f"{len(rows)} setups ({sum(r[3] == 'planned' for r in rows)} planned) -> {OUT}")
